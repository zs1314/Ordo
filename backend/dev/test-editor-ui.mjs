import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {startBoard,sleep} from './harness.mjs';
import {desktopFixture} from './desktop-fixture.mjs';
const board=await startBoard({data:desktopFixture});
let checks=0;
try {
  const page=await board.tab(board.base+'/?desktop=1',{width:1180,height:800,scale:2,network:true});
  const {ev,click,type}=page;
  const el=s=>`document.querySelector(${JSON.stringify(s)})`;
  const until=async expr=>{for(let n=0;n<80;n++){if(await ev(expr))return;await sleep(50);}throw new Error('Timed out: '+expr)};
  const check=(name,ok)=>{assert.ok(ok,name);checks++;console.log('PASS '+name)};
  const output=process.argv[2];if(output)fs.mkdirSync(output,{recursive:true});
  await click(el('.d-task[data-id="ideas"] .d-task-body'));
  await until(`!!${el('.d-task-editor')}`);await sleep(250);
  check('details use a compact sheet and do not force a title focus ring',await ev(`(() => {const b=${el('.d-task-editor')}.getBoundingClientRect();return b.width===540&&b.height<650&&b.left>200&&document.activeElement===${el('.d-task-editor')};})()`));
  check('selects have a consistent appearance and empty date says unset',await ev(`[...document.querySelectorAll('.d-task-editor select')].every(e=>getComputedStyle(e).appearance==='none')&&${el('.d-date-value')}.textContent==='未设置'`));
  const shortHeight=await ev(`${el('.d-title-input')}.clientHeight`);
  const longTitle='需要完整显示的较长任务标题，包含第二行说明，以及第三行需要保留的工作内容';
  await type(el('.d-title-input'),longTitle);
  await until(`${el('.d-title-input')}.clientHeight>${shortHeight}`);
  check('title grows to fit wrapping text without the old empty two-line box',true);
  await type(el('.d-title-input'),'记下脑海里闪过的好点子');
  await until(`${el('.d-title-input')}.clientHeight===${shortHeight}`);
  await click(el('.d-date-disclosure > summary'));
  await until(`${el('.d-date-disclosure')}.dataset.expanded==='true'`);
  await sleep(230);
  check('calendar opens inside the sheet with shortcuts',await ev(`${el('.d-mini-calendar')}.checkVisibility() && document.querySelectorAll('.d-mini-calendar [data-date]').length>=28`));
  const nextDate=await ev(`(() => {const b=${el('.d-mini-calendar button[tabindex="0"]')};b.focus();const d=new Date(b.dataset.date+'T12:00:00');d.setDate(d.getDate()+1);return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-')})()`);
  await page.key('ArrowRight','ArrowRight',39);
  await until(`document.activeElement.dataset.date===${JSON.stringify(nextDate)}`);
  check('calendar supports arrow navigation with a single tab stop',await ev(`document.querySelectorAll('.d-mini-calendar button[tabindex="0"]').length===1`));
  await page.key('Escape','Escape',27);
  await until(`!${el('.d-date-disclosure')}.open`);
  check('Escape closes the calendar first and returns focus',await ev(`!!${el('.d-task-editor')}&&document.activeElement===${el('.d-date-disclosure > summary')}`));
  await click(el('.d-date-disclosure > summary'));
  await sleep(230);
  await click(el('[aria-label="下个月"]'));
  const chosen=await ev(`[...document.querySelectorAll('.d-mini-calendar button')].find(b=>!b.classList.contains('outside')&&b.textContent==='15').dataset.date`);
  await click(el(`[data-date="${chosen}"]`));
  await until(`!${el('.d-date-disclosure')}.open`);
  check('choosing a day collapses the calendar and updates its label',await ev(`${el('.d-date-value')}.classList.contains('has-date')`));
  await click(el('.d-task-editor button[type="submit"]'));
  await until(`!${el('.d-task-editor')}`);
  check('selected calendar date persists exactly',(await board.api('GET','/api/todo')).items.find(i=>i.id==='ideas').due===chosen);
  await click(el('.d-task[data-id="ideas"] .d-task-body'));
  await click(el('.d-date-disclosure > summary'));await sleep(230);
  await click(el('[aria-label="清除日期"]'));await sleep(230);
  await click(el('.d-task-editor button[type="submit"]'));
  await until(`!${el('.d-task-editor')}`);
  check('clear date removes the stored deadline',!(await board.api('GET','/api/todo')).items.find(i=>i.id==='ideas').due);
  await click(el('.d-task[data-id="design"] .d-task-body'));await sleep(250);
  await click(el('.d-advanced > summary'));await sleep(50);
  await click(el('.d-advanced > summary'));await sleep(40);
  await click(el('.d-advanced > summary'));await sleep(260);
  check('interrupted disclosure animation settles open without fixed-height clipping',await ev(`${el('.d-advanced')}.open&&${el('[aria-label="标签"]')}.checkVisibility()&&${el('.d-advanced')}.style.height===''&&${el('.d-advanced')}.getAnimations().length===0`));
  await click(el('.d-advanced > summary'));await sleep(230);
  if(output)await page.screenshot(path.join(output,'editor-light.png'));
  await page.device({width:820,height:580,scale:1});
  check('small window keeps save actions visible with scrolling confined to content',await ev(`(() => {const r=${el('.d-task-editor')}.getBoundingClientRect(),f=${el('.d-dialog-foot')}.getBoundingClientRect();return r.top>=20&&r.bottom<=innerHeight-20&&f.bottom<=innerHeight&&${el('.d-editor-scroll')}.scrollHeight>${el('.d-editor-scroll')}.clientHeight;})()`));
  await page.media([{name:'prefers-reduced-motion',value:'reduce'}]);
  await click(el('.d-advanced > summary'));
  check('reduced motion skips disclosure animation',await ev(`${el('.d-advanced')}.getAnimations().length===0`));
  await click(el('.d-advanced > summary'));
  await page.device({width:1180,height:800,scale:2});
  await ev(`document.documentElement.dataset.mode='dark';${el('.d-editor-scroll')}.scrollTop=0`);await sleep(100);
  if(output)await page.screenshot(path.join(output,'editor-dark.png'));
  await click(el('.d-date-disclosure > summary'));
  if(output)await page.screenshot(path.join(output,'editor-calendar.png'));
  check('no runtime or request errors',page.errors.length===0);
  console.log(`${checks} editor checks passed`);
} finally {board.close()}
