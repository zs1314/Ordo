import assert from 'node:assert/strict';
import { startBoard, sleep } from './harness.mjs';
import { desktopFixture } from './desktop-fixture.mjs';
const board = await startBoard({data:doc=>{desktopFixture(doc);doc.theme.desktopStartView='agent';const task=doc.items.find(i=>i.id==='design');task.status='agent';task.agent={where:'legacy workspace',note:'saved handoff',since:'2026-01-01'};task.due='2030-01-01 AoE';}});
let checks=0;
try {
  const page=await board.tab(board.base+'/?desktop=1',{width:1180,height:800,scale:1,network:true});
  const {ev,click,type}=page;
  const el=s=>`document.querySelector(${JSON.stringify(s)})`;
  const button=t=>`[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(t)})`;
  const until=async expr=>{for(let n=0;n<70;n++){if(await ev(expr))return;await sleep(60);}throw new Error('Timed out: '+expr)};
  const check=(name,value)=>{assert.ok(value,name);checks++;console.log('PASS '+name)};
  await until(`document.querySelectorAll('.d-task').length===7`);
  check('removed startup view falls back to usable all-tasks view',await ev(`${el('h1')}.textContent==='全部待办'`));
  check('three primary views and one add-list entry',await ev(`document.querySelectorAll('[aria-label="智能清单"] button').length===3 && [...document.querySelectorAll('button')].filter(b=>b.textContent.trim()==='新建清单').length===1`));
  check('no automatic Codex entry or background connection requests',await ev(`!document.querySelector('.d-agent-panel') && !document.body.textContent.includes('Codex 协作')`) && !page.requests.some(r=>r.url.includes('/codex')));
  check('quick add precedes task list',await ev(`${el('.d-quick-entry')}.getBoundingClientRect().top<${el('.d-task')}.getBoundingClientRect().top`));
  const before=(await board.api('GET','/api/todo')).items.find(i=>i.id==='design');
  await click(el('.d-task[data-id="design"] .d-task-body'));
  await until(`!!${el('.d-inspector')}`);
  check('secondary fields start folded and exact legacy date remains editable',await ev(`!${el('.d-advanced')}.open && !${el('[aria-label="标签"]')}.checkVisibility() && ${el('[aria-label="截止日期"]')}.value==='2030-01-01 AoE'`));
  await type(el('[aria-label="任务标题"]'),'修改旧任务的标题');
  await click(button('保存修改'));
  await until(`!${el('.d-inspector')}`);
  const after=(await board.api('GET','/api/todo')).items.find(i=>i.id==='design');
  for(const field of ['status','agent','due','priority','tags','subtasks','note'])assert.deepEqual(after[field],before[field],field);
  check('editing preserves hidden legacy metadata and assignment records',true);
  await type(el('[aria-label="快速添加待办"]'),'需要补充详情的草稿');
  await click(el('[aria-label="展开新建任务详情"]'));
  await until(`!!${el('.d-composer')}`);
  check('quick-entry draft transfers into details',await ev(`${el('[aria-label="任务标题"]')}.value==='需要补充详情的草稿'`));
  await click(button('添加步骤'));
  await type(el('[aria-label="添加子任务"]'),'第一步');
  await click(el('.d-advanced > summary'));
  await type(el('[aria-label="标签"]'),'个人, 计划');
  await click(button('添加待办'));
  await until(`!${el('.d-composer')}`);
  const added=(await board.api('GET','/api/todo')).items.find(i=>i.title==='需要补充详情的草稿');
  check('expanded options persist and transferred draft clears once',added?.subtasks?.[0].title==='第一步' && added.tags.length===2 && await ev(`${el('[aria-label="快速添加待办"]')}.value==='' && !window.ordoHasUnsavedChanges()`));
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('接下来'))`);
  await until(`${el('h1')}.textContent==='接下来'`);
  await type(el('[aria-label="快速添加待办"]'),'明天要做的事');
  await until(`!!${el('.d-quick-entry button[type="submit"]')}`);
  await click(el('.d-quick-entry button[type="submit"]'));
  await until(`[...document.querySelectorAll('.d-task-title')].some(e=>e.textContent==='明天要做的事')`);
  check('upcoming quick add stays visible with tomorrow date',!!(await board.api('GET','/api/todo')).items.find(i=>i.title==='明天要做的事')?.due);
  await click(el('.d-view-options > summary'));
  check('secondary list controls reveal on demand',await ev(`${el('[aria-label="排序方式"]')}.offsetParent!==null`));
  await page.send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape'});
  await page.send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape'});
  await until(`!${el('.d-view-options')}.open`);
  check('Escape closes options and returns focus to trigger',await ev(`document.activeElement===${el('.d-view-options > summary')}`));
  check('no runtime or network errors',page.errors.length===0);
  console.log(`${checks} focused desktop checks passed`);
} finally {board.close()}
