import assert from 'node:assert/strict';
import { startBoard, sleep } from './harness.mjs';
import { desktopFixture } from './desktop-fixture.mjs';

const board = await startBoard({data:desktopFixture});
let checks=0;
try {
  const page=await board.tab(board.base+'/?desktop=1',{width:1180,height:800,scale:1,network:true});
  const {ev,click,type}=page;
  const el=s=>`document.querySelector(${JSON.stringify(s)})`;
  const button=t=>`[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(t)})`;
  const cardButton=(id,t)=>`[...document.querySelectorAll('.d-task[data-id="${id}"] button')].find(b=>b.textContent.trim()===${JSON.stringify(t)})`;
  const until=async expr=>{for(let n=0;n<80;n++){if(await ev(expr))return;await sleep(50);}throw new Error('Timed out: '+expr)};
  const saved=()=>until(`!${el('.d-save-state .saving')}`);
  const get=async id=>(await board.api('GET','/api/todo')).items.find(i=>i.id===id);
  const check=(name,ok)=>{assert.ok(ok,name);checks++;console.log('PASS '+name)};
  check('four status totals reflect active tasks',await ev(`JSON.stringify([...document.querySelectorAll('.d-status-overview strong')].map(e=>+e.textContent))==='[1,0,1,5]'`));
  await click(el('[aria-label="筛选还没做"]'));
  await until(`document.querySelectorAll('.d-task').length===5`);
  await click(cardButton('proposal','开始做'));
  await until(`!${el('.d-task[data-id="proposal"]')}`);await saved();
  check('start action updates status, totals and filtered results',(await get('proposal')).status==='doing' && await ev(`${el('[aria-label="筛选我在做"] strong')}.textContent==='2'`));
  await click(button('显示全部'));
  await until(`!!${el('.d-task[data-id="proposal"]')}`);
  await click(cardButton('proposal','等别人'));
  await until(`!!${el('[aria-label="等待事项"]')}`);
  await type(el('[aria-label="等待事项"]'),'等待团队确认排期');
  await click(button('保存修改'));
  await until(`!${el('.d-inspector')}`);
  check('waiting action records the next dependency',(await get('proposal')).status==='waiting' && await ev(`${el('.d-task[data-id="proposal"] .d-card-note')}.textContent==='等待团队确认排期'`));
  await click(cardButton('proposal','继续做'));await saved();
  check('waiting task can resume directly',(await get('proposal')).status==='doing');
  await click(cardButton('ideas','交给 Agent'));
  await until(`!!${el('.d-manual-assignment')}`);
  check('handoff is explicitly manual and starts an unsaved edit',await ev(`${el('[aria-label="任务状态"]')}.value==='agent' && document.body.textContent.includes('不会启动 Agent') && window.ordoHasUnsavedChanges()`));
  await type(el('[aria-label="Agent 运行位置"]'),'Claude Code · 本机项目');
  await type(el('[aria-label="交接说明"]'),'整理三种方案，下次确认结论');
  await click(button('保存修改'));
  await until(`!${el('.d-inspector')}`);
  let task=await get('ideas');
  check('handoff saves location, instructions and timestamps',task.status==='agent' && task.agent.where==='Claude Code · 本机项目' && task.agent.note.includes('三种方案') && !!task.agent.since && !!task.agent.lastSeen);
  await sleep(80);
  await click(cardButton('ideas','看过了'));await saved();
  const seen=await get('ideas');
  check('checked action updates follow-up time without restarting handoff',seen.agent.lastSeen>task.agent.lastSeen && seen.agent.since===task.agent.since);
  await click(cardButton('ideas','收回自己做'));await saved();
  check('reclaim keeps assignment metadata while returning to own work',(await get('ideas')).status==='doing');
  await click(button('撤销'));await saved();
  task=await get('ideas');
  check('undo reclaim restores exact handoff history',task.status==='agent' && JSON.stringify(task.agent)===JSON.stringify(seen.agent));
  await click(cardButton('ideas','做完了'));
  await until(`!${el('.d-task[data-id="ideas"]')}`);await saved();
  check('complete removes the task from active cards',(await get('ideas')).status==='done');
  await click(button('撤销'));await saved();
  task=await get('ideas');
  check('undo completion restores Agent status and history',task.status==='agent' && JSON.stringify(task.agent)===JSON.stringify(seen.agent));
  await click(el('[aria-label="筛选Agent 在做"]'));
  await until(`document.querySelectorAll('.d-task').length===1`);
  check('Agent filter shows only manual assignments',await ev(`${el('.d-task')}.dataset.id==='ideas'`));
  check('manual workflow never contacts Codex and has no runtime errors',!page.requests.some(r=>r.url.includes('/codex')) && page.errors.length===0);
  console.log(`${checks} status board checks passed`);
} finally {board.close()}
