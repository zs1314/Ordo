import assert from 'node:assert/strict';
import { startBoard, sleep } from './harness.mjs';
import { desktopFixture } from './desktop-fixture.mjs';
const board = await startBoard({data:desktopFixture});
let checks=0;
try {
  const page=await board.tab(board.base+'/?desktop=1',{width:1180,height:800,scale:2,network:true});
  const {ev,click,type}=page;
  const el=s=>`document.querySelector(${JSON.stringify(s)})`;
  const button=t=>`[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(t)})`;
  const wait=async expr=>{for(let n=0;n<50;n++){if(await ev(expr))return;await sleep(80);}throw new Error('Timed out: '+expr)};
  const check=(name,value)=>{assert.ok(value,name);checks++;console.log('PASS '+name)};
  await wait(`!!${el('.d-workspace')}`);
  check('desktop rendered seven open tasks',await ev(`document.querySelectorAll('.d-task').length===7`));
  if(process.argv[2]) await page.screenshot(process.argv[2]+'-浅色.png');
  await type(el('[aria-label="搜索所有任务"]'),'设计');
  await wait(`document.querySelectorAll('.d-task').length===1`);
  check('global search covers title, tags and notes',await ev(`${el('.d-task')}.dataset.id==='design'`));
  await type(el('[aria-label="搜索所有任务"]'),'');
  await click(el('.d-task[data-id="proposal"] .d-task-check'));
  await wait(`!${el('.d-task[data-id="proposal"]')}`);
  check('completion responds and removes task',true);
  await click(button('撤销'));
  await wait(`!!${el('.d-task[data-id="proposal"]')}`);
  check('completion undo restores previous status',true);
  await click(el('.d-task[data-id="ideas"] .d-task-star'));
  await wait(`${el('.d-task[data-id="ideas"] .d-task-star')}.classList.contains('starred')`);
  check('priority toggles with optimistic feedback',true);
  await click(el('.d-task[data-id="design"] .d-task-body'));
  await wait(`!!${el('.d-inspector')}`);
  check('task opens accessible inspector with focus',await ev(`${el('.d-workspace')}.inert && document.activeElement.matches('.d-title-input')`));
  await type(el('[aria-label="任务标题"]'),'整理设计方向 · 已编辑');
  await type(el('[aria-label="添加子任务"]'),'验证交互原型');
  await click(el('.d-subtask-add button'));
  await click(button('保存修改'));
  await wait(`!${el('.d-inspector')}`);
  let doc=await board.api('GET','/api/todo');
  check('edit and subtask changes persist',doc.items.find(i=>i.id==='design').subtasks.length===4 && doc.items.find(i=>i.id==='design').title.includes('已编辑'));
  await click(el('.d-task[data-id="ideas"] .d-task-body'));
  await click(el('[aria-label="移入回收站"]'));
  await wait(`!${el('.d-inspector')}`);
  await click(button('撤销'));
  await wait(`!!${el('.d-task[data-id="ideas"]')}`);
  check('soft delete and undo retain task metadata', (await board.api('GET','/api/todo')).items.find(i=>i.id==='ideas').priority===3);
  await type(el('[aria-label="快速添加待办"]'),'快速输入测试');
  await click(el('.d-quick-entry button'));
  await wait(`document.querySelectorAll('.d-task').length===8`);
  check('quick entry persists without losing focus',true);
  await click(button('多选'));
  await click(el('[aria-label="选择 记下脑海里闪过的好点子"]'));
  await click(el('[aria-label="选择 快速输入测试"]'));
  await click(el('[aria-label="将所选任务移入回收站"]'));
  await wait(`document.querySelectorAll('.d-task').length===6`);
  check('batch trash updates atomically', (await board.api('GET','/api/todo')).extras.trash.length===2);
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('回收站'))`);
  await wait(`document.querySelectorAll('.d-task').length===2`);
  await click(el('.d-task[data-id="ideas"] .d-button'));
  await wait(`document.querySelectorAll('.d-task').length===1`);
  check('recycle bin restore works',true);
  await ev(`window.dispatchEvent(new CustomEvent('ordo-command',{detail:'settings'}))`);
  await wait(`!!${el('.d-preferences')}`);
  await click(button('深色'));
  await wait(`document.documentElement.dataset.mode==='dark'`);
  await click(el('[aria-label="关闭设置"]'));
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('全部待办'))`);
  await wait(`!${el('.d-preferences')}`);
  await sleep(350);
  if(await ev(`!!${el('.d-toast [aria-label="关闭提示"]')}`)) await click(el('.d-toast [aria-label="关闭提示"]'));
  if(process.argv[2]) await page.screenshot(process.argv[2]+'-深色.png');
  check('dark appearance persists and renders', (await board.api('GET','/api/todo')).theme.mode==='dark');
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.trim()==='日历')`);
  await wait(`document.querySelectorAll('.d-calendar-cell').length>=28`);
  check('calendar renders month and selected-day agenda',true);
  await ev(`window.dispatchEvent(new CustomEvent('ordo-command',{detail:'new'}))`);
  await wait(`!!${el('.d-composer')}`);
  await type(el('[aria-label="任务标题"]'),'新建面板测试');
  await click(button('添加待办'));
  await wait(`!${el('.d-composer')}`);
  check('native new command saves through composer',(await board.api('GET','/api/todo')).items.some(i=>i.title==='新建面板测试'));
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('习惯打卡'))`);
  await click(el('.d-task[data-id="read"] .d-task-check'));
  await wait(`${el('.d-task[data-id="read"]')}.classList.contains('done')`);
  await sleep(250);
  check('habit check-in leaves recurring task open',(await board.api('GET','/api/todo')).items.find(i=>i.id==='read').status==='todo');
  await page.media([{name:'prefers-reduced-motion',value:'reduce'}]);
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('全部待办'))`);
  check('reduced-motion preference disables page animation',await ev(`getComputedStyle(${el('.d-page')}).animationName==='none'`));
  await page.device({width:820,height:580,scale:1});
  check('minimum window has no horizontal overflow',await ev(`document.documentElement.scrollWidth<=innerWidth && ${el('.d-main-scroll')}.scrollWidth<=${el('.d-main-scroll')}.clientWidth`));
  check('sidebar settings remain visible at minimum height',await ev(`${el('.d-sidebar-footer')}.getBoundingClientRect().bottom<=innerHeight`));
  await type(el('[aria-label="快速添加待办"]'),'暂存的输入');
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('重要'))`);
  await click(`[...document.querySelectorAll('.d-nav-item')].find(b=>b.textContent.includes('全部待办'))`);
  check('quick-entry draft survives navigation',await ev(`${el('[aria-label="快速添加待办"]')}.value==='暂存的输入' && window.ordoHasUnsavedChanges()`));
  check('no browser runtime or network errors',page.errors.length===0);
  console.log(`${checks} desktop UI checks passed`);
} finally {board.close()}
